// 大規模自動補充產品演算法 (每個子分類擴充多項產品)
(function generateFullProducts() {
    const existingIds = new Set(ALL_PRODUCTS.map(p => p.id));
    
    // 設定每個子分類產生的商品數量 (可調整，例如設為 25~30 以擴增總數)
    const ITEMS_PER_SUBCATE = 25; 

    categories.forEach(([sub_id, sub_name, main_kw, alias_list]) => {
        const main_cat = sub_id.split("_")[0];
        const brand_list = brandsMap[main_cat] || ["九乘九", "雄獅", "SKB"];

        for (let i = 1; i <= ITEMS_PER_SUBCATE; i++) {
            const pid = `${sub_id}_${String(i).padStart(3, '0')}`;
            if (existingIds.has(pid)) continue;

            const brand = brand_list[(i - 1) % brand_list.length];
            const variant = specVariants[(i - 1) % specVariants.length];

            const title = `${brand} ${main_kw} ${variant.suffix}`;
            const isEco = variant.isEco || (i % 7 === 0); // 每 7 項自動配置為環保標章
            const isNew = variant.isNew || (i % 9 === 0);

            let desc = `【萬寶企業文具】${title}。品質穩定，專為政府機關、學校與企業採購設計。`;
            if (isEco) {
                desc += " 符合行政院環境部綠色採購規範，通過國家環保標章審核認證。";
            }

            // 生成模擬真實規律的 EAN-13 條碼
            const baseCodeSeed = Math.abs(pid.split('').reduce((a, b) => { a = ((a << 5) - a) + b.charCodeAt(0); return a & a; }, 0));
            const code = `4710677${String(baseCodeSeed % 1000000).padStart(6, '0')}`;

            ALL_PRODUCTS.push({
                "id": pid,
                "img": `${pid}.jpg`,
                "title": title,
                "price": variant.price,
                "code": code,
                "spec": variant.spec,
                "desc": desc,
                "aliases": alias_list,
                "isEco": isEco,
                "isNew": isNew
            });
        }
    });
})();

